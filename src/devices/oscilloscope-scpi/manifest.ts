export type Forms = 'command' | 'query' | 'both';
export type Mutability = 'read' | 'setup' | 'destructive';
export type Response = 'text' | 'binary' | 'none';

export interface CommandEntry {
	id: string;
	subsystem: string;
	forms: Forms;
	mutability: Mutability;
	response: Response;
	owner: string;
	tools: readonly string[];
	// The reason one form or one value of the row is not covered. Rendered into docs/command-coverage.md so a
	// reader finds it without reading the source.
	note?: string;
}

type Tweak = Partial<Pick<CommandEntry, 'mutability' | 'response' | 'owner' | 'tools' | 'note'>>;
type Row = [id: string, forms: Forms, tweak?: Tweak];

