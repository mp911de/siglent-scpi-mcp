function subsystem(name: string, rows: Row[]): CommandEntry[] {
	return rows.map(([id, forms, tweak]) => ({
		id,
		subsystem: name,
		forms,
		mutability: forms === 'query' ? 'read' : 'setup',
		response: forms === 'command' ? 'none' : 'text',
		owner: '',
		tools: [],
		...tweak,
	}));
}

